/// Applies the QMC1 stream cipher in-place. Mirrors `qmc1_decrypt`.
Uint8List qmc1Decrypt(Uint8List data) {
  for (var i = 0; i < data.length; i++) {
    final keyByte = i > 0x7FFF
        ? _qmc1Key[(i % 0x7FFF) & 0x7F]
        : _qmc1Key[i & 0x7F];
    data[i] ^= keyByte;
  }
  return data;
}
